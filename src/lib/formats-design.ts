const rgbOf = (hex: string): [number, number, number] => {
  const n = parseInt(hex.replace('#', '').slice(0, 6), 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}
const hsl = ([r, g, b]: [number, number, number]) => {
  const [R, G, B] = [r / 255, g / 255, b / 255]
  const max = Math.max(R, G, B)
  const min = Math.min(R, G, B)
  const l = (max + min) / 2
  if (max === min) return [0, 0, l] as const
  const d = max - min
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min)
  const h = max === R ? (G - B) / d + (G < B ? 6 : 0) : max === G ? (B - R) / d + 2 : (R - G) / d + 4
  return [h * 60, s, l] as const
}
const hsb = ([r, g, b]: [number, number, number]) => {
  const [R, G, B] = [r / 255, g / 255, b / 255]
  const max = Math.max(R, G, B)
  const d = max - Math.min(R, G, B)
  const h = d === 0 ? 0 : max === R ? ((G - B) / d + 6) % 6 : max === G ? (B - R) / d + 2 : (R - G) / d + 4
  return [h / 6, max === 0 ? 0 : d / max, max] as const
}
const oklch = ([r, g, b]: [number, number, number]) => {
  const lin = (c: number) => ((c /= 255) <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)
  const [R, G, B] = [lin(r), lin(g), lin(b)]
  const l = Math.cbrt(0.4122214708 * R + 0.5363325363 * G + 0.0514459929 * B)
  const m = Math.cbrt(0.2119034982 * R + 0.6806995451 * G + 0.1073969566 * B)
  const s = Math.cbrt(0.0883024619 * R + 0.2817188376 * G + 0.6299787005 * B)
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s
  const Bb = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s
  const C = Math.hypot(A, Bb)
  const H = (Math.atan2(Bb, A) * 180) / Math.PI
  return [L, C, (H + 360) % 360] as const
}
const oklchCss = (hex: string) => {
  const [L, C, H] = oklch(rgbOf(hex))
  return `oklch(${(L * 100).toFixed(1)}% ${C.toFixed(3)} ${C < 0.002 ? 0 : H.toFixed(1)})`
}
const cmyk = ([r, g, b]: [number, number, number]) => {
  const k = 1 - Math.max(r, g, b) / 255
  if (k >= 1) return [0, 0, 0, 100]
  return [(1 - r / 255 - k) / (1 - k), (1 - g / 255 - k) / (1 - k), (1 - b / 255 - k) / (1 - k), k].map((v) => Math.round(v * 100))
}
const argb = (hex: string) => `0xFF${hex.replace('#', '').toUpperCase()}`
const ident = (s: string, i: number) => {
  const words = s.normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/[^A-Za-z0-9]+/g, ' ').trim().split(' ').filter(Boolean)
  if (!words.length) return `color${i + 1}`
  const id = words.map((w, j) => (j ? w[0].toUpperCase() + w.slice(1).toLowerCase() : w.toLowerCase())).join('')
  return /^[0-9]/.test(id) ? `c${id}` : id
}
const snake = (s: string, i: number) => ident(s, i).replace(/([A-Z])/g, '_$1').toLowerCase()
const kebab = (s: string, i: number) => ident(s, i).replace(/([A-Z])/g, '-$1').toLowerCase()

/** Palette colours with unique identifiers in several naming styles. */
function named(a: AestheticFull) {
  const seen = new Map<string, number>()
  return a.colors.map((c, i) => {
    let id = ident(c.name || `color ${i + 1}`, i)
    const n = seen.get(id) ?? 0
    seen.set(id, n + 1)
    if (n) id = `${id}${n + 1}`
    return { ...c, id, kebab: kebab(id, i), snake: snake(id, i), rgb: rgbOf(c.hex) }
  })
}

/** Semantic roles from the page theme (falls back to a neutral dark theme). */
function roles(a: AestheticFull) {
  const t = themeFromPalette(a.colors, a.metrics?.contrast ?? undefined)
  const v = t?.vars ?? {}
  const pick = (k: string, d: string) => (v[k] && /^#/.test(v[k]) ? v[k] : d)
  return {
    mode: t?.mode ?? 'dark',
    background: pick('--bg', '#0b0b0c'),
    surface: pick('--surface', '#131315'),
    surface2: pick('--surface-2', '#1b1b1e'),
    border: pick('--line', '#242428'),
    borderStrong: pick('--line-strong', '#34343a'),
    foreground: pick('--fg', '#f3f0ea'),
    muted: pick('--fg-muted', '#bdb8ae'),
    subtle: pick('--fg-subtle', '#8c877e'),
    primary: pick('--accent', '#e4ba6e'),
    primaryForeground: pick('--accent-fg', '#17120a'),
    secondary: pick('--accent-2', '#7fa7c9'),
    radius: Math.round(8 * Number(v['--r-scale'] ?? 1)),
  }
}
