export function toColorValues(a: AestheticFull) {
  return {
    name: a.name,
    source: pageUrl(a.slug),
    colors: named(a).map((c) => {
      const [h, s, l] = hsl(c.rgb)
      const [L, C, H] = oklch(c.rgb)
      const [cc, m, y, k] = cmyk(c.rgb)
      return {
        name: c.name,
        hex: c.hex,
        rgb: { r: c.rgb[0], g: c.rgb[1], b: c.rgb[2], css: `rgb(${c.rgb.join(' ')})` },
        hsl: { h: Math.round(h), s: Math.round(s * 100), l: Math.round(l * 100), css: `hsl(${Math.round(h)} ${Math.round(s * 100)}% ${Math.round(l * 100)}%)` },
        oklch: { l: +L.toFixed(4), c: +C.toFixed(4), h: +H.toFixed(1), css: oklchCss(c.hex) },
        cmyk: { c: cc, m, y, k, note: 'naive conversion, not colour-managed' },
      }
    }),
  }
}

