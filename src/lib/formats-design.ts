export function toShadcnCss(a: AestheticFull): string {
  const r = roles(a)
  const cs = named(a)
  const chart = [r.primary, r.secondary, ...cs.map((c) => c.hex)].slice(0, 5)
  const block = (sel: string) => `${sel} {
  --radius: ${(r.radius / 16).toFixed(3)}rem;
  --background: ${oklchCss(r.background)};
  --foreground: ${oklchCss(r.foreground)};
  --card: ${oklchCss(r.surface)};
  --card-foreground: ${oklchCss(r.foreground)};
  --popover: ${oklchCss(r.surface)};
  --popover-foreground: ${oklchCss(r.foreground)};
  --primary: ${oklchCss(r.primary)};
  --primary-foreground: ${oklchCss(r.primaryForeground)};
  --secondary: ${oklchCss(r.surface2)};
  --secondary-foreground: ${oklchCss(r.foreground)};
  --muted: ${oklchCss(r.surface2)};
  --muted-foreground: ${oklchCss(r.muted)};
  --accent: ${oklchCss(r.surface2)};
  --accent-foreground: ${oklchCss(r.foreground)};
  --destructive: oklch(0.577 0.245 27.325);
  --border: ${oklchCss(r.border)};
  --input: ${oklchCss(r.borderStrong)};
  --ring: ${oklchCss(r.primary)};
${chart.map((c, i) => `  --chart-${i + 1}: ${oklchCss(c)};`).join('\n')}
}`
  return `/* ${header(a, 'shadcn/ui theme')}
   Paste into your globals.css (replaces the default :root / .dark blocks). */
${block(':root')}

${block('.dark')}
`
}

